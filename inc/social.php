	$saved = get_option( 'plata_social_heading', '' );

	return is_string( $saved ) && '' !== $saved ? $saved : __( 'Följ oss', 'plata' );
}

/**
 * Hämta sparade sociala länkar.
 *
 * @return array<int, array{network: string, url: string}>
 */
function plata_get_social_links() {
	$saved    = get_option( 'plata_social_links', array() );
	$networks = plata_get_social_networks();
	$links    = array();

	if ( ! is_array( $saved ) ) {
		return $links;
	}

	foreach ( $saved as $item ) {
		if ( ! is_array( $item ) ) {
			continue;
		}

		$network = isset( $item['network'] ) ? sanitize_key( $item['network'] ) : '';
		$url     = isset( $item['url'] ) ? trim( (string) $item['url'] ) : '';

		if ( ! isset( $networks[ $network ] ) || '' === $url ) {
			continue;
		}

		$links[] = array(
			'network' => $network,
			'url'     => $url,
		);
	}

	return $links;
}

/**
 * Tillåtna protokoll för sociala länkar (inkl. mailto och tel).
 *
 * @return string[]
 */
function plata_get_social_allowed_protocols() {
	return array( 'http', 'https', 'mailto', 'tel' );
}

/**
 * Sanera indata för sociala länkar.
 *
 * @param mixed $input Indata från formulär.
 * @return array<int, array{network: string, url: string}>
 */
function plata_sanitize_social_links( $input ) {
	$networks  = plata_get_social_networks();
	$protocols = plata_get_social_allowed_protocols();
	$clean     = array();

	if ( ! is_array( $input ) ) {
		return $clean;
	}

	foreach ( $input as $item ) {
		if ( ! is_array( $item ) ) {
			continue;
		}

		$network = isset( $item['network'] ) ? sanitize_key( $item['network'] ) : '';
		$raw_url = isset( $item['url'] ) ? trim( (string) $item['url'] ) : '';

		if ( ! isset( $networks[ $network ] ) || '' === $raw_url ) {
			continue;
		}

		$url = esc_url_raw( $raw_url, $protocols );

		if ( '' === $url ) {
			continue;
		}

		$clean[] = array(
			'network' => $network,
			'url'     => $url,
		);
	}

	return $clean;
}

/**
 * Sanera rubriken för sociala länkar.
 *
 * @param mixed $input Indata från formulär.
 * @return string
 */
function plata_sanitize_social_heading( $input ) {
	return sanitize_text_field( (string) $input );
}

/**
 * Rendera en <select> med nätverksval.
 *
 * @param string $selected Valt nätverk.
 */
function plata_render_social_network_options( $selected = '' ) {
	foreach ( plata_get_social_networks() as $key => $network ) {
		printf(
			'<option value="%1$s" %2$s>%3$s</option>',
			esc_attr( $key ),
			selected( $selected, $key, false ),
			esc_html( $network['label'] )
		);
	}
}

